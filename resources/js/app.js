import '../css/app.css';
    
Echo.join('chat.presence') // اسم القناة التي عرفناها في channels.php
    .here((users) => {
        // هنا تحصل على قائمة بكل المستخدمين المتصلين حالياً عند دخولك
        console.log('المتواجدون الآن:', users);
        // يمكنك هنا كتابة كود لتغيير لون نقطة الحالة للأخضر للمستخدمين الموجودين في القائمة
    })
    .joining((user) => {
        // هذا الكود يعمل فور دخول مستخدم جديد
        console.log(user.name + ' أصبح متصلاً الآن');
        // تحديث الواجهة فوراً لإظهار كلمة "متصل الآن" بجانب اسمه
    })
    .leaving((user) => {
        // هذا الكود يعمل فور خروج مستخدم أو إغلاقه للمتصفح
        console.log(user.name + ' غادر الدردشة');
        // تحديث الواجهة لإظهار "آخر ظهور: منذ ثوانٍ"
    });